package com.snehashis.docmind.service;

import io.jsonwebtoken.Claims;
import io.jsonwebtoken.Jwts;
import io.jsonwebtoken.security.Keys;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.security.core.userdetails.UserDetails;
import org.springframework.stereotype.Service;

import javax.crypto.SecretKey;
import java.nio.charset.StandardCharsets;

@Service
public class JwtService {

    @Value("${jwt.secret}")
    private String secret;

    @Value("${jwt.expiration}")
    private long expiration;

    // These method getSigningKey() is used to generate a secret key for signing the JWT tokens. It uses the secret value from the application properties and converts it into a SecretKey object using the Keys.hmacShaKeyFor() method from the io.jsonwebtoken.security.Keys class. This key is then used for signing and verifying JWT tokens.
    private SecretKey getSigningKey() {;
        return Keys.hmacShaKeyFor(secret.getBytes(StandardCharsets.UTF_8));
    }

    // The generateToken(UserDetails userDetails) method is responsible for creating a JWT token for a given user. It takes the UserDetails object as input, which contains information about the authenticated user. The method sets the subject of the token to the username of the user, sets the issued date to the current date, and sets the expiration date based on the configured expiration time. Finally, it signs the token using the secret key generated by getSigningKey() and returns the compact representation of the JWT token as a String.
    public String generateToken(UserDetails userDetails) {
        return Jwts.builder()
                .subject(userDetails.getUsername())
                .issuedAt(new java.util.Date())
                .expiration(new java.util.Date(System.currentTimeMillis() + expiration))
                .signWith(getSigningKey())
                .compact();
    }

    public Claims getPayload(String token) {
        return Jwts.parser()
                .verifyWith(getSigningKey())
                .build()
                .parseSignedClaims(token)
                .getPayload();
    }

    public String extractUsername(String token) {
        return this.getPayload(token).getSubject();
    }

    public boolean isTokenExpired(String token) {
        return this.getPayload(token).getExpiration().before(new java.util.Date());
    }

    public String getIssuer(String token) {
        return this.getPayload(token).getIssuer();
    }

    public boolean isTokenValid(String token, UserDetails userDetails) {
        String username = this.extractUsername(token);
        return (username.equals(userDetails.getUsername()) && !this.isTokenExpired(token));
    }
}
